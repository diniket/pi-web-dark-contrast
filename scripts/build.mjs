// One CSS-first theme, atomically published by Pi Web's official theme registry.
// Preserve the exact official Dark palette for plugins; redesign only core roots.
import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../assets/',import.meta.url);
const parts=await Promise.all(['base-pi-web-dark.css','tokens.css','dark-contrast.css'].map(name=>readFile(new URL(name,root),'utf8')));
const generated='/* Generated by scripts/build.mjs. Official Dark baseline + isolated core redesign. */\n'+parts.join('\n');
const target=new URL('theme.css',root);
if(process.argv.includes('--check')){
 if(await readFile(target,'utf8')!==generated)throw new Error('Stale theme.css: run npm run build');
 console.log('Declarative theme matches baseline and scoped sources');
}else{
 await writeFile(target,generated);console.log('Built assets/theme.css (declarative, revision-qualified by Pi Web)');
}
